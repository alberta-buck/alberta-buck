#!/usr/bin/env node
// Bundle the forge artifacts the JS platform needs into one importable
// ES module -- the browser cannot read out/ from disk (nodefs stays
// node-only by design; buildOnePool/buildBuckWorld take an injected
// `artifacts(name)` either way).
//
//   make nix-core-js-artifacts        # writes core/js/artifacts/bundle.mjs
//
// Regenerate whenever the contracts change (the bundle test compares a
// hash against out/ and fails stale).

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

import { loadArtifact, repoRoot } from "../src/nodefs.js";

// Stage 1-3 surface: identity + BUCK stack + the V3 pool world.
export const NEEDED = [
  "MockERC20",
  "UniswapV3Factory",
  "UniswapV3Pool",
  "SimLP",
  "IdentityRegistry",
  "BuckCredit",
  "BuckKControllerDirect",
  "Buck",
];

const out = {};
for (const name of NEEDED) {
  out[name] = loadArtifact(name);
}

const dest = join(repoRoot(), "core", "js", "artifacts", "bundle.mjs");
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(
  dest,
  "// Generated by bin/bundle-artifacts.mjs -- do not edit.\n" +
  "// {abi, bytecode} per contract, from the forge out/ artifacts.\n" +
  `export const artifacts = ${JSON.stringify(out)};\n` +
  "export function artifact(name) {\n" +
  "  const a = artifacts[name];\n" +
  "  if (!a) throw new Error(`artifact not bundled: ${name}`);\n" +
  "  return a;\n" +
  "}\n",
);
const kb = Math.round(JSON.stringify(out).length / 1024);
console.log(`wrote ${dest} (${NEEDED.length} contracts, ~${kb} KB)`);
