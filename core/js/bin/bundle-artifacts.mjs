#!/usr/bin/env node
// Bundle the forge artifacts the JS platform needs into one importable
// ES module -- the browser cannot read out/ from disk (nodefs stays
// node-only by design; buildOnePool/buildBuckWorld take an injected
// `artifacts(name)` either way).
//
//   make nix-core-js-artifacts        # writes core/js/artifacts/bundle.mjs
//
// Regenerate whenever the contracts change (the bundle test compares a
// hash against out/ and fails stale).

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { loadArtifact, vendoredArtifact } from "../src/nodefs.js";

// Stage 1-3 surface: identity + BUCK stack + the V3 pool world;
// stages 5-7 add the equilibrium world's basket + real periphery.
export const NEEDED = [
  "MockERC20",
  "UniswapV3Factory",
  "UniswapV3Pool",
  "SimLP",
  "IdentityRegistry",
  "IdentityRegistryHarness",   // eq world: uncertified binds of synthetic infra
  "BuckCredit",
  "BuckCreditHarness",         // eq world: credits to proxies that never opt in
  "BuckKControllerDirect",
  "Buck",
  "WETH9",
  "BuckBasketProRata",
  "BuckBasketUniswapV3",
  "UniswapV3BindingAdapter",   // the sandbox market: pools bound on production contracts
];

const out = {};
for (const name of NEEDED) {
  out[name] = loadArtifact(name);
}
// The Universal Router and the Permit2 it pins ship as vendored artifacts
// (not forge-built here), flattened to the bundle's {abi, bytecode} shape.
for (const name of ["UniversalRouter", "Permit2"]) {
  out[name] = vendoredArtifact(name);
}

// Into THIS package, whichever checkout the artifacts were read from
// (ALBERTA_BUCK_REPO may name another).
const dest = join(dirname(fileURLToPath(import.meta.url)), "..", "artifacts", "bundle.mjs");
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(
  dest,
  "// Generated by bin/bundle-artifacts.mjs -- do not edit.\n" +
  "// {abi, bytecode} per contract, from the forge out/ artifacts.\n" +
  `export const artifacts = ${JSON.stringify(out)};\n` +
  "export function artifact(name) {\n" +
  "  const a = artifacts[name];\n" +
  "  if (!a) throw new Error(`artifact not bundled: ${name}`);\n" +
  "  return a;\n" +
  "}\n",
);
const kb = Math.round(JSON.stringify(out).length / 1024);
console.log(`wrote ${dest} (${Object.keys(out).length} contracts, ~${kb} KB)`);
